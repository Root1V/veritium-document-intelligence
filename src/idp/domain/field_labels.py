def labeled(definition: DocumentTypeDefinition) -> DocumentTypeDefinition:
    """The definition with a label on every field this table names and the type left unnamed."""
    labels = FIELD_LABELS.get(definition.key)
    if not labels:
        return definition
    fields = []
    for f in definition.fields:
        items = [i.model_copy(update={"label": i.label or labels.get(f"{f.name}[].{i.name}")}) for i in f.items] if f.items else f.items
        fields.append(f.model_copy(update={"label": f.label or labels.get(f.name), "items": items}))
    return definition.model_copy(update={"fields": fields})
